#!/usr/bin/env bash
# Download the openly licensed long-form test videos listed in docs/RESEARCH_NOTES.md into
# tests-media/ (git-ignored) and write tests-media/PROVENANCE.md. Existing complete files are
# skipped. Wikimedia asks for a descriptive User-Agent and rate-limits (HTTP 429), so requests
# identify this tool, run one at a time and retry with exponential backoff.
# Set CLIPPER_FETCH_CONTACT (e.g. an e-mail address) to add contact details to the User-Agent.
set -euo pipefail
# shellcheck source=scripts/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

DEST="$CLIPPER_ROOT/tests-media"
UA="LocalClipper-TestMediaFetcher/1.0 (personal non-commercial test fixtures${CLIPPER_FETCH_CONTACT:+; $CLIPPER_FETCH_CONTACT})"
MAX_ATTEMPTS=6

case "${1:-}" in
  "") ;;
  -h | --help) echo "Usage: scripts/fetch-test-media.sh   (downloads ~105 MB into tests-media/)"; exit 0 ;;
  *) echo "Usage: scripts/fetch-test-media.sh" >&2; exit 2 ;;
esac

# file|url|commons page|title|license|credit|bytes|sha256 (verified 2026-10-05/06)
MEDIA_LIST="$(
  cat <<'EOF'
pettit_koin_interview_pd_480p.webm|https://upload.wikimedia.org/wikipedia/commons/transcoded/e/e2/NASA_Astronaut_Don_Pettit_Talks_with_KOIN-TV%2C_Portland%2C_Oregon_-_April_16%2C_2025_%28iss072m261061434%29.webm/NASA_Astronaut_Don_Pettit_Talks_with_KOIN-TV%2C_Portland%2C_Oregon_-_April_16%2C_2025_%28iss072m261061434%29.webm.480p.vp9.webm|https://commons.wikimedia.org/wiki/File:NASA_Astronaut_Don_Pettit_Talks_with_KOIN-TV,_Portland,_Oregon_-_April_16,_2025_(iss072m261061434).webm|NASA Astronaut Don Pettit Talks with KOIN-TV, Portland, Oregon - April 16, 2025 (480p VP9 transcode)|Public domain (NASA work)|NASA|70728701|e7a29fbad7a343168bc8e2b5b3314b088ab7fbd83ab91aafb385a02c3a8abf19
fisher_copyrightx_3.1_ccby_720p.webm|https://upload.wikimedia.org/wikipedia/commons/transcoded/3/35/William_Fisher%2C_CopyrightX-_Lecture_3.1%2C_The_Subject_Matter_of_Copyright-_Literature_%28and_software%29.webm/William_Fisher%2C_CopyrightX-_Lecture_3.1%2C_The_Subject_Matter_of_Copyright-_Literature_%28and_software%29.webm.720p.vp9.webm|https://commons.wikimedia.org/wiki/File:William_Fisher,_CopyrightX-_Lecture_3.1,_The_Subject_Matter_of_Copyright-_Literature_(and_software).webm|William Fisher, CopyrightX: Lecture 3.1, The Subject Matter of Copyright: Literature (and software) (720p VP9 transcode)|CC BY 3.0 (Creative Commons Attribution 3.0; third-party excerpts are excluded from the licence)|William Fisher / Berkman Center (BerkmanCenter on Wikimedia Commons)|34605210|bbf7ecc13566664cbfde23038bb54b739eace09d4e721fe30345419f2834f469
EOF
)"

file_size() { wc -c <"$1" | tr -d ' '; }

duration_of() {
  local seconds
  if command -v ffprobe >/dev/null 2>&1; then
    seconds="$(ffprobe -v error -show_entries format=duration -of default=nw=1:nk=1 "$1" </dev/null 2>/dev/null || true)"
    if [[ "$seconds" =~ ^[0-9]+ ]]; then
      seconds="${seconds%%.*}"
      printf '%d:%02d' $((seconds / 60)) $((seconds % 60))
      return
    fi
  fi
  printf 'unknown'
}

download() { # download URL OUT EXPECTED_BYTES
  local url="$1" out="$2" expected="$3" attempt=1 delay=5
  while :; do
    if [[ -f "$out.part" && "$(file_size "$out.part")" == "$expected" ]]; then
      mv "$out.part" "$out"
      return 0
    fi
    if curl --fail --location --silent --show-error --user-agent "$UA" --connect-timeout 30 \
      --continue-at - --output "$out.part" "$url" </dev/null; then
      mv "$out.part" "$out"
      return 0
    fi
    if ((attempt >= MAX_ATTEMPTS)); then
      return 1
    fi
    echo "  Download failed (attempt $attempt of $MAX_ATTEMPTS); retrying in ${delay}s…" >&2
    sleep "$delay"
    delay=$((delay * 2))
    attempt=$((attempt + 1))
  done
}

command -v curl >/dev/null 2>&1 || die "curl is required to download the test media."
mkdir -p "$DEST"
TODAY="$(date -u +%Y-%m-%d)"
PROVENANCE="$DEST/PROVENANCE.md.tmp"
{
  echo "# Test media provenance"
  echo
  echo "Generated by scripts/fetch-test-media.sh on $TODAY. These files are git-ignored test fixtures"
  echo "and are not redistributed with the project. Licences are as stated on the Wikimedia Commons pages."
  echo
} >"$PROVENANCE"

failures=0
first=1
while IFS='|' read -r name url page title license credit bytes sha; do
  [[ -n "$name" ]] || continue
  out="$DEST/$name"
  if [[ -f "$out" && "$(file_size "$out")" == "$bytes" ]]; then
    echo "Already present: tests-media/$name"
  else
    ((first)) || sleep 2 # be polite to upload.wikimedia.org
    first=0
    echo "Downloading tests-media/$name ($((bytes / 1048576)) MB)…"
    if ! download "$url" "$out" "$bytes"; then
      echo "Could not download $name. Try again later (Wikimedia may be rate-limiting)." >&2
      failures=$((failures + 1))
      continue
    fi
  fi
  actual_sha="$(sha256_of "$out")"
  note=""
  if [[ "$actual_sha" != "$sha" ]]; then
    note=" (differs from the checksum recorded on 2026-10-06; Wikimedia may have re-encoded the transcode)"
    echo "Warning: $name has a different checksum than expected$note." >&2
  fi
  {
    echo "## $name"
    echo
    echo "- Title: $title"
    echo "- Source page: $page"
    echo "- Download URL: $url"
    echo "- Licence: $license"
    echo "- Credit: $credit"
    echo "- Duration: $(duration_of "$out")"
    echo "- Size: $(file_size "$out") bytes"
    echo "- SHA-256: $actual_sha$note"
    echo
  } >>"$PROVENANCE"
done <<<"$MEDIA_LIST"

{
  echo "## YouTube test source (not downloaded by this script)"
  echo
  echo "- https://www.youtube.com/watch?v=nKyWusznRgQ - CopyrightX Lecture 2.1 (10:02), published under the"
  echo "  YouTube \"Creative Commons Attribution license (reuse allowed)\". Imported through the app itself."
} >>"$PROVENANCE"
mv "$PROVENANCE" "$DEST/PROVENANCE.md"
echo "Wrote tests-media/PROVENANCE.md"

if ((failures)); then
  exit 1
fi
